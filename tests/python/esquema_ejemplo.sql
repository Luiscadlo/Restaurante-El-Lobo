-- ESQUEMA DE EJEMPLO para las pruebas de restauración. NO es el esquema real de Supabase.
-- ═══════════════════════════════════════════════════════════════════════════
-- Se armó a partir de las columnas que el código usa (docs/ESPECIFICO_EL_LOBO.md §2.5), con tipos
-- inventados pero razonables, y con a propósito un poco de todo lo que la herramienta debe saber copiar:
-- serial, identidad (por defecto y "siempre"), llaves foráneas, únicas, checks, índices, columnas con
-- arreglo / jsonb / numeric, una vista, una función, un disparador, un tipo enum, un dominio, una
-- secuencia suelta, comentarios y una regla RLS muy permisiva (que NO se debe copiar).
-- El esquema real se saca con sql/consulta_esquema.sql.

create type public.estado_pedido as enum ('pendiente', 'pagado');
create domain public.monto_cop as numeric(14, 2) check (value >= 0);
create sequence public.consecutivo_suelto start 100 increment 5;

create table public.clientes_fiado (
  id         bigint generated by default as identity primary key,
  nombre     text not null,
  created_at timestamptz not null default now(),
  constraint clientes_fiado_nombre_unico unique (nombre)
);
comment on table public.clientes_fiado is 'Personas a quienes se les fía';
comment on column public.clientes_fiado.nombre is 'Nombre tal como se escribe en caja';

create table public.mesas (
  id     bigserial primary key,
  numero integer not null unique,
  estado text not null default 'libre'
);

create table public.inventario (
  id     bigserial primary key,
  nombre text not null,
  unidad text not null default 'kg',
  stock  numeric(12, 3) not null default 0,
  minimo numeric(12, 3) not null default 0,
  costo  numeric(14, 2) not null default 0
);
create index inventario_nombre_idx on public.inventario (lower(nombre));

create table public.pedidos (
  id                  bigserial primary key,
  created_at          timestamptz not null default now(),
  fecha               date not null,
  hora                time,
  turno               text check (turno in ('almuerzo', 'cena')),
  mesa                integer,
  estado              public.estado_pedido not null default 'pendiente',
  pedido              text,
  detalle             text,
  cantidad            integer not null default 1 check (cantidad > 0),
  sopa                text,
  arroz               text,
  proteina            text,
  acomp               text,
  monto_unit          numeric(14, 2) default 0,
  monto_almuerzo      public.monto_cop default 0,
  monto_domicilio     numeric(14, 2) default 0,
  monto_total         numeric(14, 2) not null default 0,
  monto_efectivo      numeric(14, 2) default 0,
  monto_transferencia numeric(14, 2) default 0,
  metodo              text,
  descuento           numeric(14, 2) default 0,
  motivo_descuento    text,
  es_domicilio        boolean not null default false,
  es_fiar             boolean not null default false,
  es_gratis           boolean not null default false,
  es_sin_mesa         boolean not null default false,
  para_llevar         boolean not null default false,
  direccion           text,
  cliente_fiado_id    bigint references public.clientes_fiado (id) on delete set null,
  grupo_pedido        uuid,
  pagado_via_abono    boolean not null default false,
  fecha_pago          date,
  fecha_original      date,
  turno_pago          text
);
create index pedidos_fecha_idx on public.pedidos (fecha, turno);
create index pedidos_fiado_idx on public.pedidos (cliente_fiado_id) where es_fiar;
comment on column public.pedidos.monto_total is 'Ya con el descuento restado';

create table public.abonos_fiado (
  id               bigint generated always as identity primary key,
  created_at       timestamptz not null default now(),
  fecha            date not null,
  turno            text,
  cliente_fiado_id bigint not null references public.clientes_fiado (id) on delete cascade,
  monto            numeric(14, 2) not null check (monto > 0),
  cuenta           text not null default 'efectivo',
  nota             text
);

create table public.pedidos_eliminados (
  id         bigserial primary key,
  created_at timestamptz not null default now(),
  pedido_id  bigint,
  fecha      date,
  hora       time,
  turno      text,
  pedido     text,
  detalle    text,
  ubicacion  text,
  metodo     text,
  monto_total numeric(14, 2),
  motivo     text
);

create table public.pedidos_descuentos (
  id                   bigserial primary key,
  created_at           timestamptz not null default now(),
  pedido_ids           bigint[] not null default '{}',
  grupo_pedido         uuid,
  fecha                date,
  hora                 time,
  turno                text,
  valor_lista          numeric(14, 2),
  descuento_anterior   numeric(14, 2),
  descuento_nuevo      numeric(14, 2),
  motivo               text,
  estado_pedido        text,
  cierre_ajustado      boolean default false,
  ajuste_efectivo      numeric(14, 2) default 0,
  ajuste_transferencia numeric(14, 2) default 0,
  gastos_eliminados    text
);

create table public.consumos (
  id          bigserial primary key,
  fecha       date not null,
  producto_id bigint references public.inventario (id) on delete set null,
  nombre      text,
  cantidad    numeric(12, 3) not null,
  costo       numeric(14, 2) default 0
);

create table public.gastos_dia (
  id        bigserial primary key,
  fecha     date not null,
  turno     text,
  nombre    text not null,
  categoria text,
  monto     numeric(14, 2) not null
);

create table public.cierres_dia (
  id                   bigserial primary key,
  fecha                date not null,
  turno                text not null,
  efectivo             numeric(14, 2) default 0,
  transferencia        numeric(14, 2) default 0,
  gastos               numeric(14, 2) default 0,
  resultado            numeric(14, 2) default 0,
  platos_familia       integer default 0,
  manual               boolean default false,
  ajuste_manual        numeric(14, 2),
  ajuste_manual_nota   text,
  ajuste_efectivo      numeric(14, 2) default 0,
  ajuste_transferencia numeric(14, 2) default 0,
  abonos_efectivo      numeric(14, 2) default 0,
  abonos_transferencia numeric(14, 2) default 0,
  unique (fecha, turno)
);

create table public.aperturas_turno (
  id                           bigserial primary key,
  created_at                   timestamptz not null default now(),
  fecha                        date not null,
  turno                        text not null,
  caja_inicial                 numeric(14, 2) default 0,
  venta_desayuno               numeric(14, 2) default 0,
  venta_desayuno_transferencia numeric(14, 2) default 0
);

create table public.notas_dia (
  id         bigint generated always as identity primary key,
  created_at timestamptz not null default now(),
  fecha      date not null,
  texto      text
);

create table public.config (
  clave          text primary key,
  valor          jsonb,
  actualizado_en timestamptz not null default now()
);

create table public.configuracion (
  id            bigint generated by default as identity primary key,
  clave         text not null,
  valor         jsonb not null,
  vigente_desde timestamptz not null default now(),
  creado_por    text,
  creado_en     timestamptz not null default now()
);

create table public.egresos (
  id          bigserial primary key,
  created_at  timestamptz not null default now(),
  fecha       date not null,
  turno       text,
  cat         text,
  cuenta      text,
  description text,
  monto       numeric(14, 2) not null
);

create table public.movimientos_caja (
  id             bigserial primary key,
  created_at     timestamptz not null default now(),
  fecha          date not null,
  tipo           text not null,
  cuenta         text not null,
  cuenta_destino text,
  descripcion    text,
  monto          numeric(14, 2) not null
);

create table public.ingresos_extra (
  id          bigserial primary key,
  fecha       date not null,
  cuenta      text,
  descripcion text,
  monto       numeric(14, 2) not null
);

-- Función, disparador y vista
create function public.marcar_actualizado() returns trigger
language plpgsql as $$
begin
  new.actualizado_en := now();
  return new;
end;
$$;

create trigger config_actualizado
before update on public.config
for each row execute function public.marcar_actualizado();

create view public.ventas_por_dia as
  select fecha, turno, sum(monto_total) as total
  from public.pedidos
  where estado = 'pagado'
  group by fecha, turno;

-- Una regla vieja y abierta a todos: la herramienta NO debe copiarla al esquema nuevo.
alter table public.pedidos enable row level security;
create policy "todo abierto" on public.pedidos for all to anon using (true) with check (true);

